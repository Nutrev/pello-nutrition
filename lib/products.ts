import { THE_FEED_PRODUCTS } from "./products-thefeed";

export type Verdict = "proven" | "likely" | "disputed";
export type Goal = "muscle" | "endurance" | "recovery" | "health" | "sleep" | "immunity" | "gut health";
export type Category = "Creatine" | "Energy" | "Energy Gel" | "Carbohydrate Mix" | "Energy Chew" | "Energy Bar" | "Supplement" | "Hydration" | "Protein" | "Probiotic" | "Omega-3" | "Vitamin" | "Mineral";
export interface Ingredient {
  name: string;
  dose?: string;
  verdict: Verdict;
  note: string;
  pubmedUrl?: string;
  examineUrl?: string;
}

export interface Source {
  name: string;
  icon: string;
  count: number;
  unit: string;
  credibility: "high" | "medium" | "low";
}

// A selectable version of a product (e.g. a strength) shown on its page. Only the
// fields that differ are set; everything else comes from the product.
export interface ProductVariant {
  id: string;
  label: string;
  price: number;
  servingsPerContainer: number;
  sodiumPerServing?: number;
  rating?: number;
  reviewCount?: number;
  imageUrl?: string;
}

export interface Product {
  id: string;
  name: string;
  brand: string;
  category: Category;
  rating: number;
  reviewCount: number;
  price: number;
  goals: Goal[];
  sentiment: Record<string, number>;
  ingredients: Ingredient[];
  sources: Source[];
  transparencyScore: number;
  imageEmoji: string;
  logo?: string;
  logoSize?: "sm" | "md" | "lg";
  logoDomain?: string;
  // Servings in the pack `price` is for. When missing, a per-category default is used.
  servingsPerContainer?: number;

  // ── Structured nutrition & label data ──────────────────────
  // Optional so existing products stay valid until they're filled in. Leave a field
  // out (or null) when the label doesn't state it, rather than guessing.
  carbsPerServing?: number;        // grams
  sodiumPerServing?: number;       // mg
  caffeinePerServing?: number;     // mg (0 if caffeine-free)
  proteinPerServing?: number;      // grams
  caloriesPerServing?: number;     // kcal
  servingSize?: string;            // as on the label, e.g. "1 gel (40g)", "1 scoop (30g)"
  osmolality?: "isotonic" | "hypotonic" | "hypertonic" | null;
  glucoseFructoseRatio?: string | null;  // e.g. "1:0.8", "2:1"
  isHydrogel?: boolean;
  isBatchTested?: boolean;         // every batch third-party tested (e.g. Informed Sport, NSF)
  isVegan?: boolean;
  isGlutenFree?: boolean;
  certifications?: string[];       // e.g. ["Informed Sport", "NSF Certified for Sport"]
  allergens?: string[];            // e.g. ["milk", "soy", "tree nuts"]
  flavours?: string[];
  affiliateUrl?: string | null;
  imageUrl?: string | null;

  // Selectable versions shown on the product page. The product's own price, servings,
  // sodium and rating describe the default one (defaultVariantId).
  variants?: ProductVariant[];
  defaultVariantId?: string;
}

